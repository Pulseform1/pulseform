"""Bundle public/ into one Cloudflare Worker script (worker.js).

Requests to /api/ go to api.js (cloud saves, play stats, multiplayer rooms). The pages (index.html and games/*.html) are embedded in the script. The covers, trailers and
screenshots in public/media/ are fetched from jsDelivr, pinned to the last commit that changed
them, and cached at Cloudflare's edge, which keeps the script under the Worker size limit.
Commit and push media/ changes before running this, so jsDelivr can see them.
"""
import glob, json, os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
PUB = os.path.join(HERE, 'public')
REPO = 'Pulseform1/pulseform'
MEDIA = {'.jpg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp', '.mp4': 'video/mp4'}

sha = subprocess.check_output(['git', 'log', '-1', '--format=%H', '--', 'public/media'], cwd=HERE, text=True).strip()
assert sha, 'commit public/media first'
files = {}
for path in ['index.html'] + sorted(os.path.relpath(p, PUB) for p in glob.glob(os.path.join(PUB, 'games', '*.html'))):
    files['/' + path] = open(os.path.join(PUB, path), encoding='utf-8').read()
# version the media links in the hub page, so browsers fetch new covers and trailers after each media change
files['/index.html'] = re.sub(r'(media/[\w.-]+\.(?:jpg|png|webp|mp4))', r'\1?v=' + sha[:8], files['/index.html'])
# the game ids from the hub's GAMES list, so /api/play only counts real games
games_src = files['/index.html'].split('const GAMES = [', 1)[1].split('const CATEGORIES', 1)[0]
game_ids = sorted(set(re.findall(r'''\n\s*id:\s*['"]([a-z0-9-]+)['"]''', games_src)))
assert game_ids, 'no game ids found in index.html'
media = {'/media/' + n: MEDIA[os.path.splitext(n)[1]] for n in sorted(os.listdir(os.path.join(PUB, 'media')))}

src = '''// Generated by build-worker.py from public/. Do not edit by hand.
import { api, Saves, Stats, Rooms } from './api.js';
export { Saves, Stats, Rooms };
const GAME_IDS = %s;
const FILES = %s;
const MEDIA = %s;
const CDN = 'https://cdn.jsdelivr.net/gh/%s@%s/pulsebox/public';

export default {
  async fetch(request, env, ctx) {
    if (new URL(request.url).pathname.startsWith('/api/')) return api(request, env, ctx, GAME_IDS);
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    let path = new URL(request.url).pathname;
    if (path === '/') path = '/index.html';
    const type = MEDIA[path];
    if (type) {
      const range = request.headers.get('range');
      const upstream = await fetch(CDN + path, { headers: range ? { range } : {}, cf: { cacheEverything: true, cacheTtl: 2592000 } });
      if (!upstream.ok) return new Response('Media unavailable, try again shortly.', { status: 502 });
      const headers = { 'content-type': type, 'cache-control': 'public, max-age=604800', 'accept-ranges': 'bytes' };
      for (const h of ['content-length', 'content-range']) if (upstream.headers.has(h)) headers[h] = upstream.headers.get(h);
      return new Response(request.method === 'HEAD' ? null : upstream.body, { status: upstream.status, headers });
    }
    const body = FILES[path];
    if (body === undefined) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    return new Response(request.method === 'HEAD' ? null : body, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-cache' } });
  }
};
''' % (json.dumps(game_ids), json.dumps(files, ensure_ascii=False), json.dumps(media), REPO, sha)
open(os.path.join(HERE, 'worker.js'), 'w', encoding='utf-8').write(src)
print('worker.js', len(src.encode()), 'bytes,', len(game_ids), 'game ids, media pinned to', sha[:7])
