"""Builds a testing site for games that are not on Pulsebox yet: a small Worker of its own on workers.dev (separate from
the pulsebox Worker and box.pulseform.org), each page tagged TEST SITE and kept out of search engines, with a plain list
of the games at /.
  python3 tools/test-site.py <out-dir> <worker-name> public/games/<page>.html [...]
then in out-dir:  npx wrangler deploy
The pages are packed into worker.js (static asset uploads are refused through the session proxy, as for Pulsebox)."""
import json, os, re, sys, html

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out, name, pages = sys.argv[1], sys.argv[2], sys.argv[3:]
assert re.fullmatch(r'[a-z0-9-]{3,40}', name) and pages, 'usage: test-site.py <out-dir> <worker-name> <pages...>'
os.makedirs(out, exist_ok=True)
TAG = ('<div style="position:fixed;bottom:8px;left:50%;transform:translateX(-50%);z-index:99999;background:#f2b33d;color:#1a1200;'
       'font:700 11px system-ui;padding:3px 9px;border-radius:9px;pointer-events:none;letter-spacing:.08em">TEST SITE</div>')
files, links = {}, []
for p in pages:
    s = open(os.path.join(HERE, p) if not os.path.isabs(p) else p, encoding='utf-8').read()
    s = re.sub(r'<meta charset="?utf-8"?>', lambda m: m.group(0) + '\n<meta name="robots" content="noindex,nofollow">', s, count=1, flags=re.I)
    s = s.replace('</body>', TAG + '\n</body>', 1)
    base = os.path.basename(p); files['/' + base] = s
    t = re.search(r'<title>([^<]*)</title>', s); links.append((base, t.group(1) if t else base))
files['/index.html'] = ('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
  '<meta name="robots" content="noindex,nofollow"><title>Pulsebox testing site</title>'
  '<body style="font:16px system-ui;background:#0b0e14;color:#eee;max-width:640px;margin:40px auto;padding:0 16px">'
  '<h1 style="font-size:22px">Pulsebox testing site</h1><p style="color:#aab">Games being tested before they go on Pulsebox.</p><ul>' +
  ''.join('<li style="margin:10px 0"><a style="color:#c6ff3d;font-size:18px" href="/%s">%s</a></li>' % (b, html.escape(t)) for b, t in links) + '</ul></body>')
src = '''// A testing site for games not yet on Pulsebox (generated by tools/test-site.py; not box.pulseform.org).
const FILES = %s;
export default {
  async fetch(request) {
    let path = new URL(request.url).pathname;
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    if (path === '/') path = '/index.html'; else if (!path.endsWith('.html') && FILES[path + '.html']) path += '.html';
    const body = FILES[path];
    if (body === undefined) return new Response('Not found. Start at /', { status: 404, headers: { 'content-type': 'text/plain' } });
    return new Response(request.method === 'HEAD' ? null : body, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-cache', 'x-robots-tag': 'noindex, nofollow', 'x-content-type-options': 'nosniff' } });
  }
};
''' % json.dumps(files, ensure_ascii=False)
open(os.path.join(out, 'worker.js'), 'w', encoding='utf-8').write(src)
acct = next(l.split('=')[1].strip().strip('"') for l in open(os.path.join(HERE, 'wrangler.toml')) if l.startswith('account_id'))
open(os.path.join(out, 'wrangler.toml'), 'w').write(f'''# A testing site for Pulsebox games not yet on the hub: separate from the pulsebox Worker and box.pulseform.org.
name = "{name}"
main = "worker.js"
account_id = "{acct}"
compatibility_date = "2026-10-01"
workers_dev = true
preview_urls = false
''')
print(f'test site {name}: {len(files)} pages, worker.js {os.path.getsize(os.path.join(out, "worker.js")) // 1024} KB in {out}')
