"""Builds the testing site for the educational games: a small Worker of its own (pulsebox-learn-test on workers.dev),
separate from the pulsebox Worker and box.pulseform.org. Every page is tagged TEST SITE and kept out of search engines;
the category page is also at /.
  python3 tools/learn-test-site.py [out-dir]     (default /tmp/learn-test-site), then in out-dir:  npx wrangler deploy
The pages are packed into worker.js (static asset uploads are refused through the session proxy, as for Pulsebox)."""
import glob, json, os, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = sys.argv[1] if len(sys.argv) > 1 else '/tmp/learn-test-site'
os.makedirs(out, exist_ok=True)
subprocess.run([sys.executable, os.path.join(HERE, 'tools', 'build-learn.py')], check=True, stdout=subprocess.DEVNULL)
TAG = ('<div style="position:fixed;bottom:8px;left:50%;transform:translateX(-50%);z-index:99;background:#f2b33d;color:#1a1200;'
       'font:700 11px system-ui;padding:3px 9px;border-radius:9px;pointer-events:none;letter-spacing:.08em">TEST SITE</div>')
files = {}
for f in sorted(glob.glob(os.path.join(HERE, 'public', 'games', 'learn*.html'))):
    s = open(f, encoding='utf-8').read()
    s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="robots" content="noindex,nofollow">', 1).replace('</body>', TAG + '\n</body>', 1)
    files['/' + os.path.basename(f)] = s
files['/index.html'] = files['/learn.html']
src = '''// The testing site for the Pulsebox educational games (generated by tools/learn-test-site.py; not box.pulseform.org).
const FILES = %s;
export default {
  async fetch(request) {
    let path = new URL(request.url).pathname;
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    if (path === '/') path = '/index.html'; else if (!path.endsWith('.html') && FILES[path + '.html']) path += '.html';
    const body = FILES[path];
    if (body === undefined) return new Response('Not found. Start at /', { status: 404, headers: { 'content-type': 'text/plain' } });
    return new Response(request.method === 'HEAD' ? null : body, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-cache', 'x-robots-tag': 'noindex, nofollow', 'x-content-type-options': 'nosniff' } });
  }
};
''' % json.dumps(files, ensure_ascii=False)
open(os.path.join(out, 'worker.js'), 'w', encoding='utf-8').write(src)
acct = next(l.split('=')[1].strip().strip('"') for l in open(os.path.join(HERE, 'wrangler.toml')) if l.startswith('account_id'))
open(os.path.join(out, 'wrangler.toml'), 'w').write(f'''# Testing site for the Pulsebox educational games: separate from the pulsebox Worker and box.pulseform.org.
name = "pulsebox-learn-test"
main = "worker.js"
account_id = "{acct}"
compatibility_date = "2026-10-01"
workers_dev = true
preview_urls = false
''')
print(f'learn test site: {len(files)} pages, worker.js {os.path.getsize(os.path.join(out, "worker.js")) // 1024} KB in {out}; deploy with: cd {out} && npx wrangler deploy')
