"""Voice a speaker's lines with Dia (Apache-2.0, Nari Labs): very natural, conversational speech with real breaths,
laughs and gasps. Used for Jay in Unknown Number.

    python tools/voices_dia.py <film> [id ...]        (no ids = every line whose speaker has "engine": "dia")

A speaker with "engine": "dia" in script.json names a short voice prompt in voices/refs/ (`prompt`) and its transcript
(`promptText`). The prompt was itself generated by Dia from a random seed (no real person's voice is copied), and
every line is generated as a continuation of it, so the voice stays the same from line to line. A line's `dia` text
(with tags like (laughs), (gasps), (chuckle), (exhales)) is what Dia performs; `text` is what has to be heard.
Each take is cut after its last expected word (whisper word timestamps), checked against `text`, and redone with a
new seed if it doesn't match (best of 4). Writes public/films/<film>/vo/<id>.wav and stores each line's `dur`.

Setup: the same environment as tools/voices_chatterbox.py, with transformers >= 4.53 (Dia support). Downloads
nari-labs/Dia-1.6B-0626 and descript/dac_44khz (about 6.5 GB) on first run. Runs at about 20x real time on 4 CPU cores.
"""
import difflib, json, re, sys, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
import numpy as np, soundfile as sf, torch
from transformers import AutoProcessor, DiaForConditionalGeneration
from faster_whisper import WhisperModel

ROOT = Path(__file__).resolve().parent.parent
film, only = sys.argv[1], set(sys.argv[2:])
fdir = ROOT / "public" / "films" / film; spath = fdir / "script.json"; (fdir / "vo").mkdir(parents=True, exist_ok=True)
script = json.loads(spath.read_text())
torch.set_num_threads(4)
CK = "nari-labs/Dia-1.6B-0626"
proc = AutoProcessor.from_pretrained(CK); model = DiaForConditionalGeneration.from_pretrained(CK, torch_dtype=torch.float32).eval()
asr = WhisperModel("base.en", device="cpu", compute_type="int8")

NUM = {"seventy-seven": "77", "forty-seven": "47", "two forty-seven": "2 47", "three-oh-two": "3 02", "ten": "10", "two": "2", "three": "3", "five": "5"}
def norm(s):   # compare what was said with what was meant: no tags, times and numbers as digits, the web address as one word
    s = re.sub(r"\([^)]*\)", " ", s.lower()).replace("box dot pulseform dot org", "boxpulseformorg").replace("box.pulseform.org", "boxpulseformorg")
    s = re.sub(r"(\d)[:.](\d\d)", r"\1 \2", s)
    for k, v in sorted(NUM.items(), key=lambda kv: -len(kv[0])): s = re.sub(rf"\b{k}\b", v, s)
    return re.sub(r"[^a-z0-9 ]+", " ", s).split()
def take(prompt, ptext, text, seed, max_tokens):
    torch.manual_seed(seed); np.random.seed(seed)
    inputs = proc(text=[ptext + " " + text], audio=[prompt], padding=True, return_tensors="pt", sampling_rate=44100)
    plen = proc.get_audio_prompt_len(inputs["decoder_attention_mask"])
    with torch.inference_mode():
        out = model.generate(**inputs, max_new_tokens=max_tokens, guidance_scale=3.0, temperature=1.8, top_p=0.90, top_k=45)
    tmp = fdir / "vo" / "_take.wav"; proc.save_audio(proc.batch_decode(out, audio_prompt_len=plen), str(tmp))
    w, sr = sf.read(tmp); tmp.unlink(); return (w if w.ndim == 1 else w.mean(1)), sr
def cut(w, sr, want):   # keep up to the end of the last expected word (Dia sometimes keeps talking); trim the front
    import librosa
    y16 = librosa.resample(w.astype(np.float32), orig_sr=sr, target_sr=16000)
    segs, _ = asr.transcribe(y16, beam_size=5, word_timestamps=True)
    words = [x for s in segs for x in s.words]; got = norm(" ".join(x.word for x in words))
    end = len(w) / sr
    if words:   # the shortest prefix of the take that best says the line
        r = [difflib.SequenceMatcher(None, norm(" ".join(x.word for x in words[:k])), want).ratio() for k in range(1, len(words) + 1)]
        k = int(np.argmax(r)); end = words[k].end if r[k] > 0.5 else end
    w = w[: min(len(w), int((end + 0.28) * sr))]
    db = 20 * np.log10(np.abs(w) + 1e-7); idx = np.where(db > db.max() - 40)[0]; a = max(0, idx[0] - int(sr * 0.06)) if len(idx) else 0
    w = w[a:]; f = int(sr * 0.04); w[-f:] *= np.linspace(1, 0, f)
    y16 = librosa.resample(w.astype(np.float32), orig_sr=sr, target_sr=16000)
    heard = norm(" ".join(s.text for s in asr.transcribe(y16, beam_size=5)[0]))
    return w, difflib.SequenceMatcher(None, heard, want).ratio(), " ".join(heard)

def level(w, sr, target):   # same speech level from line to line (hushed lines a little quieter), peaks under -1 dBFS
    n = int(sr * 0.05); r = np.array([np.sqrt(np.mean(w[i:i + n] ** 2)) for i in range(0, len(w) - n, n)]); r = r[r > r.max() * 0.1]
    g = 10 ** ((target - 20 * np.log10(np.sqrt(np.mean(r ** 2)))) / 20); return w * min(g, 0.89 / (np.abs(w).max() + 1e-9))

for spk, v in script["voices"].items():
    if v.get("engine") != "dia": continue
    pw, psr = sf.read(ROOT / "voices" / "refs" / v["prompt"]); pw = pw if pw.ndim == 1 else pw.mean(1)
    if psr != 44100:
        import librosa; pw = librosa.resample(pw, orig_sr=psr, target_sr=44100)
    for line in script["lines"]:
        if line["who"] != spk or (only and line["id"] not in only): continue
        want = norm(line["text"]); text = v["promptText"].rstrip() + " " + line.get("dia", line["text"])
        best = None
        for seed in range(4):
            w, sr = take(pw.astype(np.float32), v["promptText"], line.get("dia", line["text"]), 100 + seed * 7 + len(line["id"]), int((len(want) * 0.6 + 3.5) * 86))
            w, score, heard = cut(w, sr, want)
            print(f"  {line['id']} seed {seed}: {score:.2f} {len(w)/sr:.2f}s \"{heard}\"", flush=True)
            if not best or score > best[1]: best = (w, score, sr)
            if score >= 0.9: break
        w, score, sr = best; w = level(w, sr, v.get("level", -19) - (2 if line.get("mood") == "whisper" else 0)); sf.write(fdir / "vo" / f"{line['id']}.wav", w, sr); line["dur"] = round(len(w) / sr, 3)
        print(f"{line['id']}: {line['dur']}s (match {score:.2f})", flush=True)
        spath.write_text(json.dumps(script, indent=1, ensure_ascii=False) + "\n")
