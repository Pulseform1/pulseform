"""Bundle public/ into one Cloudflare Worker script (worker.js).

The small app files are embedded in the script. The two large engine files are
fetched from public CDNs (byte-identical to the copies in public/) and cached
at Cloudflare's edge, which keeps the script well under the Worker size limit.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PUB = os.path.join(HERE, 'public')
TYPES = {'.html': 'text/html; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.txt': 'text/plain; charset=utf-8'}
EMBED = ['index.html', 'app.js', 'openings.js', 'pieces.js', 'puzzles.js', 'sf19.js', 'sf19s.js', 'STOCKFISH-LICENSE.txt']
LONG = {'pieces.js', 'puzzles.js', 'sf19.js', 'sf19s.js'}
REMOTE = {
    '/sf19.wasm': ['https://unpkg.com/stockfish@19.0.1/bin/stockfish-19-lite.wasm', 'application/wasm'],
    '/sf19s.wasm': ['https://unpkg.com/stockfish@19.0.1/bin/stockfish-19-lite-single.wasm', 'application/wasm'],
    '/stockfish.js': ['https://cdn.jsdelivr.net/npm/stockfish.js@10.0.2/stockfish.js', 'application/javascript; charset=utf-8'],
}

files = {}
for name in EMBED:
    body = open(os.path.join(PUB, name), encoding='utf-8').read()
    cache = 'public, max-age=86400' if name in LONG else 'no-cache'
    files['/' + name] = [TYPES[os.path.splitext(name)[1]], body, cache]

src = '''// Generated by build-worker.py from public/. Do not edit by hand.
const FILES = %s;
const REMOTE = %s;

// Cross-origin isolation unlocks SharedArrayBuffer, which multi-threaded Stockfish needs.
const ISOLATE = { 'cross-origin-opener-policy': 'same-origin', 'cross-origin-embedder-policy': 'credentialless', 'cross-origin-resource-policy': 'same-origin' };

export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    const path = new URL(request.url).pathname === '/' ? '/index.html' : new URL(request.url).pathname;
    const remote = REMOTE[path];
    if (remote) {
      const upstream = await fetch(remote[0], { cf: { cacheEverything: true, cacheTtl: 2592000 } });
      if (!upstream.ok) return new Response('Engine file unavailable, try again shortly.', { status: 502 });
      return new Response(upstream.body, { headers: { 'content-type': remote[1], 'cache-control': 'public, max-age=604800', ...ISOLATE } });
    }
    const file = FILES[path];
    if (!file) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    return new Response(request.method === 'HEAD' ? null : file[1], { headers: { 'content-type': file[0], 'cache-control': file[2], ...ISOLATE } });
  }
};
''' % (json.dumps(files, ensure_ascii=False), json.dumps(REMOTE))
open(os.path.join(HERE, 'worker.js'), 'w', encoding='utf-8').write(src)
print('worker.js', len(src.encode()), 'bytes')
