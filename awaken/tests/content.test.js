// Contract signing, optional quests, shop/gear/deal, consumables, shadow extraction.
const { assert, quiet, awaken, clearSession, page } = require('./helpers');
(async () => {
  const { b, p, errors } = await page();
  await awaken(p, 'Signer');
  const sig = await p.evaluate(() => S.player.sig || '');
  assert(/^data:image\/png;base64,/.test(sig) && sig.length > 500, 'the contract signature is saved'); await quiet(p);
  await p.click('[data-a=tab][data-x=status]');
  assert(await p.locator('.sig-img').count() === 1, 'the signature shows in the Status window');
  await p.evaluate(() => { S.daily.grace = false; S.daily.rest = false; retarget(); });
  await p.click('[data-a=tab][data-x=quest]');
  assert(await p.locator('[data-a=side]').count() === 5, 'five optional quests a day');
  const before = await p.evaluate(() => S.daily.side.map(q => q.id));
  await p.click('[data-a=sideReroll]'); await p.click('[data-a=side][data-x="2"]');
  const after = await p.evaluate(() => ({ ids: S.daily.side.map(q => q.id), done: S.daily.side[2].done }));
  assert(after.ids[2] !== before[2] && !after.done && after.ids.filter((x, i) => x !== before[i]).length === 1, 'Swap one replaces exactly the tapped quest');
  assert(await p.locator('[data-a=sideReroll]').count() === 0, 'the swap is once a day');
  const gold0 = await p.evaluate(() => S.player.gold);
  for (let i = 0; i < 5; i++) await p.click(`[data-a=side][data-x="${i}"]`);
  const full = await p.evaluate(() => ({ full: S.daily.sideFull, heads: [curN && curN.head, ...NQ.map(n => n.head)] }));
  assert(full.full && full.heads.includes('Full Discipline') && await p.evaluate(g => S.player.gold > g, gold0), 'clearing all five pays the Full Discipline bonus');
  await quiet(p);
  await p.evaluate(() => { S.player.gold = 20000; refresh(); });
  await p.click('[data-a=tab][data-x=items]'); await p.click('[data-a=itemsTab][data-x=shop]');
  const strBefore = await p.evaluate(() => bonus('str'));
  await p.click('[data-a=buyGear][data-x=knuckle]');
  const eq = await p.evaluate(() => ({ eq: S.gear.eq.weapon, str: bonus('str') }));
  assert(eq.eq === 'knuckle' && Math.abs(eq.str - strBefore - .03) < 1e-9, 'buying gear auto-equips it and adds its bonus');
  await p.click('[data-a=buyGear][data-x=dagger]'); await p.click('[data-a=itemsTab][data-x=gear]'); await p.click('[data-a=equip2][data-x=dagger]');
  assert(await p.evaluate(() => S.gear.eq.weapon === 'dagger'), 'one weapon at a time: equipping swaps it');
  await p.click('[data-a=itemsTab][data-x=shop]'); await p.click('[data-a=buyDeal]');
  assert(await p.evaluate(() => S.daily.dealBought && dailyDeal().bought), 'the daily deal can be claimed once');
  await p.evaluate(() => { S.inv.compass = 1; });
  const g0 = await p.evaluate(() => S.gates.list.map(g => g.id).join());
  await p.evaluate(() => useItem('compass'));
  assert(await p.evaluate(g0 => { const g1 = S.gates.list.map(g => g.id).join(); return g0 !== g1 && g1.includes('-r1-'); }, g0), "Gate Compass rerolls today's gates");
  await p.evaluate(() => { S.inv.scroll = 1; useItem('scroll'); S.player.mp = 100; enterGate(S.gates.list[0].id); });
  await quiet(p);
  await clearSession(p); await p.waitForTimeout(200);
  const ex = await p.evaluate(() => { const n = [curN, ...NQ].find(x => x && x.head === 'Shadow Extraction'); if (!n) return { offered: false };
    const r = Math.random; Math.random = () => 0; n.onChoose('arise'); Math.random = r; return { offered: true, army: Object.keys(S.shadows).length, scroll: S.buffs.scroll }; });
  assert(ex.offered && ex.army === 1 && ex.scroll === false, 'a cleared gate offers Arise; extraction adds a shadow and uses the XP Scroll ' + JSON.stringify(ex));
  await quiet(p);
  assert(await p.evaluate(() => { for (const id of Object.keys(SHADOWS)) S.shadows[id] = { lv: 5 }; return Math.max(...ARMY_KEYS.map(armyBonus)); }) <= .25 + 1e-9, 'army bonuses are capped at +25%');
  await p.setViewportSize({ width: 320, height: 640 }); const over = [];
  for (const t of ['inv', 'gear', 'shop', 'army']) { await p.evaluate(t => { UI.tab = 'items'; UI.itemsTab = t; refresh(); }, t); const w = await p.evaluate(() => document.documentElement.scrollWidth); if (w > 320) over.push(t + ':' + w); }
  assert(over.length === 0, 'no sideways scrolling at 320 px on Items tabs (' + over.join(',') + ')');
  assert(errors.length === 0, 'no page errors ' + JSON.stringify(errors));
  await b.close();
})();
