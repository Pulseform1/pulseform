# Builds sprites.js from sprite batch files: python3 tools/build-sprites.py <folder with b*.json>
# Each batch file holds {"sprites":[{"id","name","size","palette":{char:"#rrggbb"},"rows":[...]}]}; "." is transparent.
import json, glob, os, sys
src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sprites.js')
sprites = []
for f in sorted(glob.glob(os.path.join(src, 'b*.json'))):
    for sp in json.load(open(f))['sprites']:
        n = sp['size']
        assert len(sp['rows']) == n and all(len(r) == n for r in sp['rows']), sp['id']
        assert all(c == '.' or c in sp['palette'] for r in sp['rows'] for c in r), sp['id']
        sprites.append(sp)
lines = ['/* Awaken pixel-art sprites: enemies (32x32) and gear (16x16).',
         '   Each sprite: n = size, p = palette (one character per color), r = rows ("." is transparent).',
         '   Generated by tools/build-sprites.py; edit the rows here or in the source batches. */',
         'window.SPRITES={']
for sp in sprites:
    lines.append(f"// {sp.get('name', sp['id'])}")
    lines.append(f"{json.dumps(sp['id'])}:{{n:{sp['size']},p:{json.dumps(sp['palette'], separators=(',', ':'))},r:[")
    lines += [f"  {json.dumps(r)}," for r in sp['rows']]
    lines.append(']},')
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(sprites), 'sprites ->', os.path.relpath(out), os.path.getsize(out), 'bytes')
